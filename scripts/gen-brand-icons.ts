/**
 * Extracts only the brand logos the catalog uses into src/lib/brand-icons.generated.ts, so the
 * client bundle never ships the full icon sets (they are ~10 MB of dev-only JSON).
 *
 *   npx tsx scripts/gen-brand-icons.ts
 *
 * Sources: `logos:*` = @iconify-json/logos (full-colour logos), `si:*` = simple-icons (single-path,
 * painted in the official brand colour), `mdi:*` = Material Design Icons Microsoft glyphs, painted in
 * the Microsoft product colour (simple-icons no longer ships Microsoft marks).
 */
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { ALL_BLOCKS } from "../src/lib/catalog";

const require = createRequire(import.meta.url);
const logos = require("@iconify-json/logos/icons.json");
const mdi = require("@iconify-json/mdi/icons.json");
const simple = require("simple-icons");

const MDI_COLOR: Record<string, string> = {
  "microsoft-office": "#D83B01",
  "microsoft-outlook": "#0A64AD",
  "microsoft-sharepoint": "#0364B8",
};

type Out = { body: string; w: number; h: number };

// eslint-disable-next-line @typescript-eslint/no-explicit-any
function iconify(set: any, name: string): Out {
  const own = set.icons[name] ?? set.icons[set.aliases?.[name]?.parent];
  if (!own) throw new Error(`icon not found: ${name}`);
  return { body: own.body, w: own.width ?? set.width ?? 16, h: own.height ?? set.height ?? 16 };
}

/**
 * Several logos define gradients / clip paths with generic ids ("a", "b", …). Rendered inline, the same
 * id from two different logos collides and one of them paints wrong, so give every icon its own prefix.
 */
function uniqueIds(body: string, prefix: string): string {
  const found = [...body.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]);
  let result = body;
  for (const id of new Set(found)) {
    const esc = id.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    result = result
      .replace(new RegExp(`(\\sid=")${esc}"`, "g"), `$1${prefix}${id}"`)
      .replace(new RegExp(`url\\(#${esc}\\)`, "g"), `url(#${prefix}${id})`)
      .replace(new RegExp(`((?:xlink:)?href=")#${esc}"`, "g"), `$1#${prefix}${id}"`);
  }
  return result;
}

const ids = [...new Set(ALL_BLOCKS.map((b) => b.icon.brand).filter((x): x is string => !!x))].sort();
const out: Record<string, Out> = {};
for (const id of ids) {
  const [src, name] = id.split(":");
  if (src === "logos") out[id] = iconify(logos, name);
  else if (src === "mdi") {
    const i = iconify(mdi, name);
    out[id] = { ...i, body: i.body.replace(/<path /g, `<path fill="${MDI_COLOR[name]}" `) };
  } else if (src === "si") {
    const key = "si" + name[0].toUpperCase() + name.slice(1);
    const s = simple[key];
    if (!s) throw new Error(`simple-icon not found: ${name}`);
    out[id] = { body: `<path fill="#${s.hex}" d="${s.path}"/>`, w: 24, h: 24 };
  } else throw new Error(`unknown source in ${id}`);
  out[id].body = uniqueIds(out[id].body, `b${ids.indexOf(id)}-`);
}

const banner = "// GENERATED by scripts/gen-brand-icons.ts — do not edit.\n";
const body = `export const BRAND_ICONS: Record<string, { body: string; w: number; h: number }> = ${JSON.stringify(out, null, 1)};\n`;
writeFileSync(new URL("../src/lib/brand-icons.generated.ts", import.meta.url), banner + body);
console.log(`wrote ${ids.length} logos (${Math.round(body.length / 1024)} KB)`);
